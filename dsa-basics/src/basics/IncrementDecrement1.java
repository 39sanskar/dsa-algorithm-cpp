package basics;

public class IncrementDecrement1 {
    public static void main(String[] args) {
        int x = 10;
        int y = x++;  // here value of x is 11 and value of y is 10
        System.out.println(x+" "+y);  // 11 10
        System.out.println(y+" "+x);  // 10 11
    }
}


