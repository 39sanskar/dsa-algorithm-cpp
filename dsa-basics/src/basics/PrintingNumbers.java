package basics;

public class PrintingNumbers {
    public static void main(String[] args) {
        System.out.println(21);  // this is Number
        System.out.println("21"); // this is Text

        System.out.println(21 + 1);
        System.out.println("21 + 1");

        System.out.println("hello 21 + 1");  // hello 21 + 1
    }
}
