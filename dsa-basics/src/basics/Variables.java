package basics;


public class Variables {
    public static void main(String[] args) {
        int x = 5;
        System.out.println(x + 7);
        int y; // declaration
        y = 20; // initialization
        System.out.println(y);

        System.out.println(x * y);

        // Modifying values of Variables
        int z = 7;
        System.out.println(z);
        z = z + 2;
        System.out.println(z);

        z = z - 4;
        System.out.println(z);

        z = z * 10;
        System.out.println(z);

        z = z / 5;
        System.out.println(z);
    }
}

