package basics;

public class ArithmeticOperationsOnInt {
    public static void main(String[] args) {
        int x = 39, y = 10;
        System.out.println(x + y); // 49
        System.out.println(x - y); // 29
        System.out.println(x * y); // 390
        System.out.println(x / y); // 3

        double a = 39, b = 10;
        System.out.println(a + b); // 49.0
        System.out.println(a - b); // 29.0
        System.out.println(a * b); // 390.0
        System.out.println(a / b);  // 3.9


    }
}
