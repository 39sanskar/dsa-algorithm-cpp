package basics;

public class VariableNaming {
    public static void main(String[] args) {

        int sanskar = 100;
        System.out.println(sanskar);

        int INT = 2;      // allow in variable name but when write in small (int) then it is not allow.
        System.out.println(INT);

    }
}


/*

Variable naming Rules
    1. Variables can start from alphabets or _ or $ (variable should not start from number...)
    2. Special characters except _ and $ are not allowed
    3. Blanks, Commas not allowed
    4. Keywords not allowed

    // allowed in variable name => _ or alphabet or $
    // not allowed in variable name => ! @ # % ^ & * ( ) _ - + = ~ ` [ ] { } \ | : ; ' " < > , . / ?

*/

